#!/usr/bin/env python3
"""Build the Grafana dashboards under apps/homelab/monitoring/grafana/dashboards/.

  python3 -I scripts/11-dashboards.py            build: definitions (*.py) -> JSON, regenerate the ConfigMap list, validate
  python3 -I scripts/11-dashboards.py check      fail if any generated file is stale (nothing written)
  python3 -I scripts/11-dashboards.py --live [name ...]
                                                 also run every query (metrics against VictoriaMetrics, LogsQL against
                                                 VictoriaLogs; port-forwarded automatically, or --vm-url / --vl-url URL)
                                                 and report empty or failing panels

Each sub-folder is one Grafana folder (title-cased name). Any *.json in it is used as is; a *.py builds the
*.json of the same name (it must set `dashboard = Board(...)`, see scripts/dashboards/dashlib.py).
"""
import json
import pathlib
import re
import runpy
import socket
import subprocess
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

REPO = pathlib.Path(__file__).resolve().parent.parent
GRAFANA = REPO / "apps/homelab/monitoring/grafana"
DASHBOARDS = GRAFANA / "dashboards"
KUSTOMIZATION = GRAFANA / "kustomization.yaml"
FOLDER_LIMIT = 900 * 1024
# Literal datasource uids a panel may use; anything else must be a variable like ${datasource}.
ALLOWED_DS = {"victoriametrics", "victorialogs", "__expr__", "grafana", "-- Grafana --", "-- Mixed --", "-- Dashboard --"}
LOGS_TYPES = {"victoriametrics-logs-datasource"}

sys.path.insert(0, str(REPO / "scripts/dashboards"))


def render_definitions():
    out = {}
    for py in sorted(DASHBOARDS.glob("*/*.py")):
        board = runpy.run_path(str(py), run_name="__dashboard__").get("dashboard")
        if board is None:
            sys.exit(f"{py.relative_to(REPO)}: does not set `dashboard`")
        out[py.with_suffix(".json")] = json.dumps(board.json(), indent=2) + "\n"
    return out


def kustomization_text(files):
    lines = ["# Generated by scripts/11-dashboards.py from the folders under dashboards/; do not edit by hand.",
             "apiVersion: kustomize.config.k8s.io/v1beta1", "kind: Kustomization", "namespace: monitoring",
             "resources:", "  - grafana.yaml", "generatorOptions:", "  disableNameSuffixHash: true", "  labels:",
             '    grafana_dashboard: "1"', "configMapGenerator:"]
    for folder in sorted({p.parent.name for p in files}, key=lambda f: (f != "homelab", f)):
        lines += [f"  - name: dashboards-{folder}", "    options:", "      annotations:",
                  f"        grafana_folder: {folder.title()}", "    files:"]
        lines += [f"      - dashboards/{folder}/{p.name}" for p in sorted(files) if p.parent.name == folder]
    return "\n".join(lines) + "\n"


def walk_panels(panels):
    for p in panels:
        yield p
        yield from walk_panels(p.get("panels", []))


def validate(contents):
    errors, uids, sizes = [], {}, {}
    for path, text in sorted(contents.items()):
        rel = path.relative_to(REPO)
        sizes[path.parent.name] = sizes.get(path.parent.name, 0) + len(text.encode())
        try:
            d = json.loads(text)
        except json.JSONDecodeError as e:
            errors.append(f"{rel}: invalid JSON: {e}")
            continue
        uid = d.get("uid")
        if not uid:
            errors.append(f"{rel}: no uid")
        elif uid in uids:
            errors.append(f"{rel}: uid {uid} also used by {uids[uid]}")
        else:
            uids[uid] = rel
        for p in walk_panels(d.get("panels", [])):
            for obj in [p] + list(p.get("targets") or []):
                ds = obj.get("datasource")
                u = ds.get("uid") if isinstance(ds, dict) else ds
                if isinstance(u, str) and u and not u.startswith("$") and u not in ALLOWED_DS:
                    errors.append(f"{rel}: panel '{p.get('title')}' uses datasource uid '{u}'")
    for folder, size in sizes.items():
        if size > FOLDER_LIMIT:
            errors.append(f"dashboards/{folder}: {size // 1024} KiB, over the {FOLDER_LIMIT // 1024} KiB limit; split it into two generators")
    return errors


# ------------------------------------------------------------------ live query check
BUILTIN = {"__rate_interval": "2m", "__interval": "30s", "__range": "1h", "__range_s": "3600", "__auto_interval": "1m", "__interval_ms": "30000"}


def get(base, path, **params):
    with urllib.request.urlopen(f"{base}{path}?{urllib.parse.urlencode(params, doseq=True)}", timeout=30) as r:
        return json.load(r)


def subst(expr, vals):
    def rep(m):
        name = (m.group(1) or m.group(2) or m.group(3)).split(":")[0]
        return BUILTIN.get(name, vals.get(name, m.group(0)))
    for _ in range(3):
        expr = re.sub(r"\$\{(\w+(?::\w+)?)\}|\[\[(\w+)\]\]|\$(\w+)", rep, expr)
    return expr


def var_values(base, v, vals):
    t = v.get("type")
    if t in ("custom", "interval"):
        opts = [o.get("value") for o in v.get("options", []) if o.get("value") not in (None, "$__auto_interval")]
        return opts or [x.strip() for x in str(v.get("query", "")).split(",") if x.strip()] or ["1m"]
    if t in ("constant", "textbox"):
        return [str(v.get("query") or "")]
    if t != "query" or (v.get("datasource") or {}).get("type") in LOGS_TYPES:
        return None
    q = v.get("query")
    q = subst((q.get("query") if isinstance(q, dict) else q) or "", vals).strip()
    try:
        m = re.match(r"label_values\((.*),\s*([\w.]+)\s*\)$", q, re.S)
        bare = re.match(r"label_values\(\s*([\w.]+)\s*\)$", q)
        if m:
            r = get(base, f"/api/v1/label/{m.group(2)}/values", **{"match[]": m.group(1)})["data"]
        elif bare:
            r = get(base, f"/api/v1/label/{bare.group(1)}/values")["data"]
        elif q.startswith("query_result("):
            r = [json.dumps(x["metric"]) for x in get(base, "/api/v1/query", query=q[13:-1])["data"]["result"]]
        elif q:
            r = [s.get("__name__", "") + "{" + ",".join(f'{k}="{x}"' for k, x in s.items() if k != "__name__") + "}"
                 for s in get(base, "/api/v1/series", **{"match[]": q})["data"]]
        else:
            r = []
    except (urllib.error.URLError, KeyError, ValueError):
        r = []
    rx = (v.get("regex") or "").strip()
    if rx and r:
        body = rx[1:rx.rfind("/")] if rx.startswith("/") else rx
        try:
            pat = re.compile(re.sub(r"\(\?<(\w+)>", r"(?P<\1>", body))
            out = set()
            for x in r:
                mm = pat.search(x)
                if mm:
                    gd = mm.groupdict()
                    out.add(gd.get("value") or gd.get("text") or (mm.group(1) if mm.groups() else x))
            r = sorted(out)
        except re.error:
            pass
    return r


def logs_query(vl, t):
    now = int(time.time())
    qt, q = t.get("queryType") or "instant", t["expr"]
    if qt == "statsRange":
        return len(get(vl, "/select/logsql/stats_query_range", query=q, start=now - 21600, end=now, step="5m")["data"]["result"])
    if qt == "stats":
        return len(get(vl, "/select/logsql/stats_query", query=q, time=now)["data"]["result"])
    with urllib.request.urlopen(f"{vl}/select/logsql/query?{urllib.parse.urlencode({'query': q, 'start': now - 21600, 'end': now, 'limit': 5})}", timeout=30) as r:
        return sum(1 for line in r.read().decode().splitlines() if line.strip())


def live_check(base, vl, path, text):
    d = json.loads(text)
    vals = {}
    for v in d.get("templating", {}).get("list", []):
        if v.get("type") == "datasource":
            vals[v["name"]] = "victoriametrics"
            continue
        r = var_values(base, v, vals)
        if r is None:
            continue
        multi = v.get("multi") or v.get("includeAll")
        vals[v["name"]] = ("(" + "|".join(r) + ")" if multi and len(r) > 1 else r[0]) if r else (".*" if multi else "")
    ok, problems = 0, []
    for p in walk_panels(d.get("panels", [])):
        pds = p.get("datasource") if isinstance(p.get("datasource"), dict) else {}
        for t in p.get("targets") or []:
            tds = t.get("datasource") if isinstance(t.get("datasource"), dict) else pds
            is_logs = (tds or {}).get("type") in LOGS_TYPES
            if not t.get("expr") or t.get("hide") or (is_logs and not vl):
                continue
            try:
                n = logs_query(vl, t) if is_logs else len(get(base, "/api/v1/query", query=subst(t["expr"], vals))["data"]["result"])
                if n:
                    ok += 1
                else:
                    problems.append(("empty", p.get("title"), t["expr"]))
            except urllib.error.HTTPError as e:
                problems.append(("ERROR", p.get("title"), f"{t['expr']} :: {e.read().decode()[:200]}"))
    return ok, problems


def port_forward(svc, target):
    s = socket.socket(); s.bind(("127.0.0.1", 0)); port = s.getsockname()[1]; s.close()
    proc = subprocess.Popen(["kubectl", "-n", "monitoring", "port-forward", f"svc/{svc}", f"{port}:{target}"],
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    base = f"http://127.0.0.1:{port}"
    for _ in range(40):
        try:
            urllib.request.urlopen(f"{base}/health", timeout=1)
            return proc, base
        except OSError:
            time.sleep(0.25)
    proc.kill()
    return None, None


def main():
    args = sys.argv[1:]
    check_only = "check" in args
    live = "--live" in args
    vm_url = args[args.index("--vm-url") + 1] if "--vm-url" in args else None
    vl_url = args[args.index("--vl-url") + 1] if "--vl-url" in args else None
    names = [a for a in args if a not in ("check", "--live", "--vm-url", vm_url, "--vl-url", vl_url)]

    generated = render_definitions()
    contents = {p: p.read_text() for p in DASHBOARDS.glob("*/*.json") if p not in generated}
    contents.update(generated)
    wanted = dict(generated)
    wanted[KUSTOMIZATION] = kustomization_text(list(contents))

    errors = validate(contents)
    stale = [p for p, text in wanted.items() if not p.exists() or p.read_text() != text]
    if check_only:
        for p in stale:
            print(f"stale: {p.relative_to(REPO)}")
        for e in errors:
            print(f"ERROR: {e}")
        sys.exit(1 if stale or errors else 0)
    if errors:
        sys.exit("\n".join(f"ERROR: {e}" for e in errors) + "\nNothing written.")
    for p in stale:
        p.write_text(wanted[p])
        print(f"wrote {p.relative_to(REPO)}")
    print(f"{len(contents)} dashboards in {len({p.parent for p in contents})} folders, all valid; {len(stale)} file(s) changed")

    if live:
        proc, base = (None, vm_url) if vm_url else port_forward("victoria-metrics", 8428)
        if not base:
            sys.exit("could not port-forward to VictoriaMetrics (is kubectl pointed at the lab?)")
        vl_proc, vl = (None, vl_url) if vl_url else port_forward("victoria-logs", 9428)
        if not vl:
            print("VictoriaLogs not reachable; log panels are skipped")
        try:
            for p in sorted(contents):
                if names and p.stem not in names and p.name not in names:
                    continue
                ok, problems = live_check(base, vl, p, contents[p])
                print(f"\n{p.relative_to(DASHBOARDS)}: {ok} queries with data, {len(problems)} empty or failing")
                for kind, title, expr in problems:
                    print(f"   {kind}: [{title}] {expr[:220]}")
        finally:
            for pr in (proc, vl_proc):
                if pr:
                    pr.kill()


if __name__ == "__main__":
    main()
